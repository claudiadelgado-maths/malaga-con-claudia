  const supportedLanguages = Object.keys(dictionaries);

  function storedLanguage() {
    const queryLanguage = new URLSearchParams(window.location.search).get("lang");
    if (supportedLanguages.includes(queryLanguage)) return queryLanguage;

    try {
      const savedLanguage = window.sessionStorage.getItem("malaga-language");
      return supportedLanguages.includes(savedLanguage) ? savedLanguage : "es";
    } catch (_error) {
      return "es";
    }
  }

  function translate(language) {
    const selected = supportedLanguages.includes(language) ? language : "es";
    const dictionary = dictionaries[selected];

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;
      if (dictionary[key] !== undefined) element.textContent = dictionary[key];
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      const key = element.dataset.i18nAriaLabel;
      if (dictionary[key] !== undefined) element.setAttribute("aria-label", dictionary[key]);
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
      const key = element.dataset.i18nAlt;
      if (dictionary[key] !== undefined) element.setAttribute("alt", dictionary[key]);
    });

    document.querySelectorAll("[data-lang]").forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.lang === selected));
    });

    document.documentElement.lang = selected;
    document.title = metadata[selected].title;
    document.querySelector('meta[name="description"]')?.setAttribute("content", metadata[selected].description);
    document.querySelector('meta[property="og:title"]')?.setAttribute("content", metadata[selected].title);
    document.querySelector('meta[property="og:description"]')?.setAttribute("content", metadata[selected].description);

    try {
      window.sessionStorage.setItem("malaga-language", selected);
    } catch (_error) {
      // The interface still works when storage is disabled.
    }

    window.dispatchEvent(new CustomEvent("languagechange", { detail: { language: selected } }));
  }

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => translate(button.dataset.lang));
  });

  const initialLanguage = storedLanguage();
  translate(initialLanguage);

  window.MalagaI18n = {
    dictionaries,
    metadata,
    get language() {
      return document.documentElement.lang;
    },
    translate
  };
